import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stringify } from 'yaml';

import { readDesignTokens, renderTokensCss } from '../scripts/build.mjs';

const BUILD_SCRIPT = fileURLToPath(new URL('../scripts/build.mjs', import.meta.url));

function baseTokens() {
  return {
    colors: {
      primary: '#2E63CC',
      'on-primary': '#FFFFFF',
      'dark-primary': '#548AF7',
      'dark-on-primary': '#101114',
    },
    typography: {
      'body-md': {
        fontFamily: 'system sans',
        fontSize: '12px',
        fontWeight: 400,
        lineHeight: '1.3',
      },
    },
    spacing: { xs: '4px' },
    rounded: { md: '3px' },
    components: {
      'button-primary': {
        backgroundColor: '{colors.primary}',
        textColor: '{colors.on-primary}',
      },
    },
  };
}

function fixture(tokens = baseTokens()) {
  return `---\n${stringify({ version: 'alpha', name: 'Fixture', ...tokens })}---\n\n# Fixture\n`;
}

function fixtureWithout(group) {
  const tokens = baseTokens();
  delete tokens[group];
  return fixture(tokens);
}

function block(css, selector) {
  const start = css.indexOf(selector);
  assert.notEqual(start, -1, `missing selector ${selector}`);
  const open = css.indexOf('{', start);
  const close = css.indexOf('}', open);
  return css.slice(open + 1, close);
}

// Review focus: encoding.
test('front matter must start at byte 0', () => {
  const markdown = `\n${fixture()}`;
  assert.throws(() => readDesignTokens(markdown), /front matter/);
});

test('CRLF front matter is tolerated', () => {
  const lf = fixture();
  const crlf = lf.replace(/\n/g, '\r\n');
  assert.deepEqual(readDesignTokens(crlf), readDesignTokens(lf));
  assert.equal(
    renderTokensCss(readDesignTokens(crlf)),
    renderTokensCss(readDesignTokens(lf)),
  );
});

test('keeps YAML token order', () => {
  const tokens = baseTokens();
  tokens.colors = {
    zeta: '#111111',
    alpha: '#222222',
    'dark-zeta': '#333333',
    'dark-alpha': '#444444',
  };
  const css = renderTokensCss(readDesignTokens(fixture(tokens)));
  const root = block(css, ':root');
  const dark = block(css, '[data-theme="dark"]');
  assert.ok(root.indexOf('--color-zeta') < root.indexOf('--color-alpha'));
  assert.ok(dark.indexOf('--color-zeta') < dark.indexOf('--color-alpha'));
});

// Review focus: state.
test('every light color is in :root and every dark color overrides it', () => {
  const tokens = readDesignTokens(fixture());
  const css = renderTokensCss(tokens);
  const root = block(css, ':root');
  const dark = block(css, '[data-theme="dark"]');
  const media = block(css, ':root:not([data-theme])');

  assert.match(css, /@media \(prefers-color-scheme: dark\)/);
  assert.match(root, /color-scheme: light;/);
  assert.match(dark, /color-scheme: dark;/);
  assert.match(media, /color-scheme: dark;/);

  for (const [name, value] of Object.entries(tokens.colors)) {
    if (name.startsWith('dark-')) {
      const base = name.slice('dark-'.length);
      const declaration = `--color-${base}: ${value.toLowerCase()};`;
      assert.ok(dark.includes(declaration), `${declaration} missing from dark block`);
      assert.ok(media.includes(declaration), `${declaration} missing from media block`);
    } else {
      const declaration = `--color-${name}: ${value.toLowerCase()};`;
      assert.ok(root.includes(declaration), `${declaration} missing from :root`);
    }
  }
});

// Review focus: file.
test('creates dist and reruns byte-identically', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'design-build-'));
  try {
    await writeFile(join(dir, 'DESIGN.md'), fixture(), 'utf8');
    const first = spawnSync(process.execPath, [BUILD_SCRIPT], { cwd: dir, encoding: 'utf8' });
    assert.equal(first.status, 0, first.stderr);
    const outputPath = join(dir, 'dist', 'tokens.css');
    const firstCss = await readFile(outputPath, 'utf8');
    assert.match(firstCss, /Generated by scripts\/build\.mjs/);
    assert.ok(firstCss.endsWith('\n'));

    const second = spawnSync(process.execPath, [BUILD_SCRIPT], { cwd: dir, encoding: 'utf8' });
    assert.equal(second.status, 0, second.stderr);
    assert.equal(await readFile(outputPath, 'utf8'), firstCss);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

// Review focus: protocol errors.
test('rejects missing group', () => {
  for (const group of ['colors', 'typography', 'spacing', 'rounded', 'components']) {
    assert.throws(() => readDesignTokens(fixtureWithout(group)), new RegExp(group));
  }
});

test('rejects unpaired dark', () => {
  const tokens = baseTokens();
  delete tokens.colors.primary;
  assert.throws(() => readDesignTokens(fixture(tokens)), /dark-primary.*primary/);
});

test('rejects duplicate variable names', () => {
  const markdown = `---\ncolors:\n  primary: "#2E63CC"\n  primary: "#111111"\n---\n`;
  assert.throws(() => readDesignTokens(markdown), /duplicate variable name/i);
});

// Named tests from the task contract.
test('renders both themes', () => {
  const tokens = readDesignTokens(fixture());
  const css = renderTokensCss(tokens);
  const root = block(css, ':root');
  const dark = block(css, '[data-theme="dark"]');
  const media = block(css, ':root:not([data-theme])');

  assert.match(root, /--color-primary: #2e63cc;/);
  assert.match(dark, /--color-primary: #548af7;/);
  assert.match(media, /--color-primary: #548af7;/);
  assert.match(root, /--space-xs: 4px;/);
  assert.match(root, /--radius-md: 3px;/);
  assert.match(root, /--text-body-md-size: 12px;/);
  assert.match(root, /--font-body-md:/);
});

test('hides raw dark names', () => {
  const css = renderTokensCss(readDesignTokens(fixture()));
  assert.doesNotMatch(css, /--color-dark-/);
});

test('deterministic', () => {
  const tokens = readDesignTokens(fixture());
  assert.equal(renderTokensCss(tokens), renderTokensCss(tokens));
});
