#!/usr/bin/env node
// Renders the token source (src/lib/tokens/tokens.json) into plain CSS custom
// properties, then writes src/lib/styles/tokens.css and dist/tokens.css.
// Run directly: node scripts/build-tokens.mjs
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const tokensFile = join(root, "src/lib/tokens/tokens.json");

/** @type {{ prim: { light: Record<string, string>, dark: Record<string, string> }, light: Record<string, string>, dark: Record<string, string> }} */
export const tokens = JSON.parse(readFileSync(tokensFile, "utf8"));

/**
 * @param {Record<string, string>} declarations
 * @param {string} indent
 */
function render(declarations, indent = "  ") {
  return Object.entries(declarations)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join("\n");
}

/**
 * @param {string} theme
 * @returns {Record<string, string>}
 */
function primitives(theme) {
  return tokens.prim[theme === "dark" ? "dark" : "light"];
}

/**
 * @param {"light" | "dark"} theme
 * @returns {Record<string, string>}
 */
function resolved(theme) {
  return { ...tokens.light, ...tokens[theme] };
}

/**
 * Builds the full stylesheet: the root theme, the explicit theme scopes, the
 * prefers-color-scheme fallback, and the line and density container scopes.
 * Every value is written literally, so density is listed and never derived.
 * @param {"light" | "dark"} [theme] the theme declared on :root
 * @returns {string}
 */
export function buildTokensCss(theme = "light") {
  const defaultTheme = theme === "dark" ? "dark" : "light";
  const rootBody = render({
    ...prefixedPrimitives(defaultTheme),
    ...resolved(defaultTheme),
  });
  const lightBody = render({
    ...prefixedPrimitives("light"),
    ...resolved("light"),
  });
  const darkBody = render({
    ...prefixedPrimitives("dark"),
    ...tokens.dark,
  });

  return `/* Generated by scripts/build-tokens.mjs from src/lib/tokens/tokens.json. Do not edit. */
:root {
${rootBody}
}

@media (pointer: coarse) {
  :root {
    --row-h: 44px;
    --row-h-sm: 36px;
    --control-h: 36px;
  }
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${darkBody}
  }
}

[data-theme="light"] {
${lightBody}
}

[data-theme="dark"] {
${darkBody}
}

[data-lines="none"] {
  --border-alpha: 0;
}

[data-lines="visible"] {
  --border-alpha: .16;
}

[data-density="compact"] {
  --row-h: 32px;
  --row-h-sm: 28px;
  --control-h: 24px;
}

[data-density="comfortable"] {
  --row-h: 44px;
  --row-h-sm: 36px;
  --control-h: 36px;
}
`;
}

/**
 * @param {"light" | "dark"} theme
 * @returns {Record<string, string>}
 */
function prefixedPrimitives(theme) {
  /** @type {Record<string, string>} */
  const out = {};
  for (const [name, value] of Object.entries(primitives(theme))) {
    out[`prim-${name}`] = value;
  }
  return out;
}

export function writeTokenFiles() {
  const css = buildTokensCss();
  const styles = join(root, "src/lib/styles/tokens.css");
  const dist = join(root, "dist/tokens.css");
  mkdirSync(dirname(styles), { recursive: true });
  mkdirSync(dirname(dist), { recursive: true });
  writeFileSync(styles, css);
  writeFileSync(dist, css);

  const layouts = join(root, "src/lib/styles/layouts.css");
  if (existsSync(layouts)) {
    copyFileSync(layouts, join(root, "dist/layouts.css"));
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeTokenFiles();
}
