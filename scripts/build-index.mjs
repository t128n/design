#!/usr/bin/env node
// Generates src/lib/index.ts from the component, view, theme and icon folders.
//
// The package barrel is generated once so no component task has to edit a
// shared file. Every .svelte file becomes a named default export; exported
// types are picked up from the per-folder index.ts files.
//
// Usage:
//   node scripts/build-index.mjs            regenerate src/lib/index.ts
//   node scripts/build-index.mjs --package  generate, build dist, prune tests
//   node scripts/build-index.mjs --prune    drop compiled tests from dist
import {
  existsSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, extname, join, relative } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const lib = join(root, "src/lib");
const sourceRoots = ["components", "views", "theme", "icons"].map((name) =>
  join(lib, name),
);

/** @param {string} dir @returns {string[]} */
function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

/** @param {string} file @returns {string} */
function specifier(file) {
  return `./${relative(lib, file).replace(/\\/g, "/")}`;
}

/**
 * Collect the exported type names from every per-folder index.ts. Type-only
 * exports cannot be inferred from a .svelte file, so they keep their source
 * index module.
 * @returns {{ name: string, from: string }[]}
 */
function collectTypes() {
  const types = new Map();
  const indexes = sourceRoots.flatMap((dir) =>
    walk(dir).filter((file) => basename(file) === "index.ts"),
  );

  for (const index of indexes) {
    const source = readFileSync(index, "utf8");
    const spec = specifier(index).replace(/\.ts$/, "");
    for (const block of source.matchAll(/export\s*\{([^}]*)\}\s*from\s*["'][^"']+["']/g)) {
      for (const match of block[1].matchAll(/\btype\s+([A-Za-z0-9_]+)/g)) {
        types.set(match[1], spec);
      }
    }
    for (const block of source.matchAll(/export\s+type\s*\{([^}]*)\}\s*from\s*["'][^"']+["']/g)) {
      for (const match of block[1].matchAll(/\b([A-Za-z0-9_]+)\b/g)) {
        types.set(match[1], spec);
      }
    }
  }

  return [...types].map(([name, from]) => ({ name, from })).sort((a, b) =>
    a.name.localeCompare(b.name),
  );
}

function buildIndex() {
  const components = sourceRoots
    .flatMap((dir) => walk(dir).filter((file) => extname(file) === ".svelte"))
    .map((file) => ({ name: basename(file, ".svelte"), from: specifier(file) }))
    .sort((a, b) => a.name.localeCompare(b.name));

  const names = new Set();
  for (const { name } of components) {
    if (names.has(name)) throw new Error(`Duplicate component export: ${name}`);
    names.add(name);
  }

  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const lines = [
    "// Generated by scripts/build-index.mjs. Do not edit by hand.",
    "// Run `node scripts/build-index.mjs` or `npm run package` to regenerate.",
    "",
    `export const version = ${JSON.stringify(pkg.version)};`,
    "",
  ];

  for (const { name, from } of components) {
    lines.push(`export { default as ${name} } from "${from}";`);
  }

  const types = collectTypes();
  if (types.length > 0) lines.push("");
  for (const { name, from } of types) {
    lines.push(`export type { ${name} } from "${from}";`);
  }

  writeFileSync(join(lib, "index.ts"), `${lines.join("\n")}\n`);
}

/** Remove compiled test files from dist (svelte-package v3 has no exclude). */
function pruneDist() {
  const dist = join(root, "dist");
  for (const file of walk(dist)) {
    if (/\.(test|spec)\.[^/]+$/.test(file)) rmSync(file);
  }
}

/**
 * Runs svelte-package through its API so the `package.exclude` declaration in
 * svelte.config.js can stay in place: the v3 CLI rejects that legacy key, while
 * the API ignores it and this script prunes the test output afterwards.
 */
async function packageDist() {
  // @sveltejs/package only exports its package.json, so resolve the API entry
  // next to it instead of importing the package by name.
  const require = createRequire(import.meta.url);
  const pkgEntry = require.resolve("@sveltejs/package/package.json");
  const { build } = await import(
    pathToFileURL(join(dirname(pkgEntry), "src/index.js")).href
  );
  const { default: config } = await import(
    pathToFileURL(join(root, "svelte.config.js")).href
  );
  const { package: _exclude, ...packageConfig } = config;

  await build({
    cwd: root,
    input: "src/lib",
    output: "dist",
    preserve_output: false,
    types: true,
    config: packageConfig,
  });

  pruneDist();

  const { writeTokenFiles } = await import("./build-tokens.mjs");
  writeTokenFiles();
}

const args = process.argv.slice(2);

if (args.includes("--prune")) {
  pruneDist();
} else if (args.includes("--package")) {
  buildIndex();
  await packageDist();
} else {
  buildIndex();
}
